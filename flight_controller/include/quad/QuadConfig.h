// ============================================================
//  § 7-4  s5c : 高度ホールド (スロットルPID)
// ============================================================
//  構造 (カスケード。位置ホールドと同じ考え方):
//    高度誤差[m] ──[ALT_POS_KP]──► 目標上昇速度[m/s] ──[ALT_RATE PID]──►
//        スロットル補正[割合] ──► (係留時に掴んだホバースロットル) + 補正
//
//  ★★ これまで「スロットルは全モード手動」が安全上の不変条件だった。
//     s5c ではこのループを足す。実飛行では PC を繋げないので、ON/OFF は
//     シリアル 'g' ではなく SW_AUTO スイッチで行う
//     (drone_s5.cpp の S5::ALT_HOLD_ON_SW_AUTO = true)。
//       SW_HOVER=up  → POSHOLD (水平ホールド)。ここまではスロットル手動。
//       + SW_AUTO=up → 高度ホールドも ON。
//       SW_AUTO=down → 高度だけ手動に戻る (水平ホールドは維持)。
//       SW_HOVER=down→ ANGLE + 完全手動 (最終 bail-out)。
//
//  ★ ホバースロットルの基準:
//     ALT_HOVER_THR (>0) にあらかじめ実測値を入れておく。これが
//     基準スロットルになり、PID はそこから ±ALT_THR_AUTH だけ動かす。
//     ALT_HOVER_THR = 0 のままだと高度ホールドは engage しない (安全)。
//     ※ 実測方法: ANGLE で安定ホバリングさせ、そのときのスロットル
//        スティック位置 (プロポの%) を読む。0.45〜0.55 が一般的。
//
//  ★ 保持高度: ALT_TARGET_M。0 なら「engage した瞬間の実測高度」。
//     飛行中はスロットルスティックを基準から動かすと上昇/下降速度指令、
//     戻すとその高度を保持する。

// 外側 (位置): 高度誤差[m] → 目標上昇速度[m/s]。kp=1 なら 1m ずれで 1m/s。
// ★ 2026-09-05: 20〜50cmを行き来し続ける振動を受けて 2.0 -> 1.0 に下げた。
//   kp=2.0 だと誤差0.2m(VZ_LIM/kp)を切るまで常に上限0.4m/sに張り付く、
//   ほぼオンオフに近い制御になっていた (目標50cmなら30cmを切るまで減速が
//   始まらない)。kp=1.0ならその範囲が0.4mまで広がり、もっと早くから
//   なめらかに減速する。
//   ★ ただし別途確認中の「制御ループが818ms〜4.3秒停止する」問題が
//     残っている場合、この振動はPIDではなくその停止が原因の可能性が高い。
//     StallLog ('w') で停止が無いことを確認してから、この変更の効果を
//     判断すること。
// ★ 2026-09-06(3): log_035 で t=3〜8s の減衰振動(周期~1s、振幅は
//   0.40m→0.27m/2.5周期 = 1周期あたり約13%減衰)を確認。発散はしていないが
//   遅れ(~0.3〜0.5秒)に対してはまだ強めで収束が遅い。3.0 -> 2.0。
constexpr float ALT_POS_KP     = 2.0f;
// ★ 2026-09-06: 10.0 -> 0.8。クランプ撤去(10.0)だと外側ループが 1.9m の
//   誤差に対し -5.7 m/s の降下を要求していた(log_033)。機体が安全に出せる
//   鉛直速度は ~1 m/s。0.8 に制限すると kp=3.0 のままでも誤差 0.27m 以内が
//   線形域、それ以上は一定 0.8 m/s 指令で頭打ち。
constexpr float ALT_POS_VZ_LIM = 0.8f;      // 位置ループが出す上昇速度の上限 [m/s]

// 内側 (速度): (目標 - 実測 上昇速度[m/s]) → スロットル補正[割合]
//  kp=0.25 なら「0.4 m/s ずれていたら +0.10 スロットル」
// ★ 2026-09-05: 1Hz前後の遅い上下振動 (50cm超えでスロットルが急に抜け、
//   30cmまで沈んでまたゆっくり上がる、を繰り返す) を受けて ki / I上限を
//   下げた。測距(約33ms周期)+ RANGE_H_ALPHA/RANGE_VZ_ALPHA の二重LPFで
//   フィードバックに数百msの遅れがあるのに ki=0.15 (積分時定数1.7秒) は
//   速すぎ、実際に効くころには行き過ぎた分だけI項が巻き上がって反転が
//   遅れ、リミットサイクルになっていたと考えられる。
//   ki: 0.15 -> 0.05 (積分時定数を5秒相当まで伸ばす)。
//   I_LIMIT: 0.15 -> 0.05 (I項単独で出力(ALT_THR_AUTH=0.15)を
//     振り切れないようにし、P/D項の反応余地を残す)。
// ★ 2026-09-06(2): 0.4 -> 0.3。log_035 の減衰振動(周期~1s)対策。ALT_POS_KP
//   と同時に下げて、遅れに対する過剰反応を減らす。
constexpr float ALT_RATE_KP      = 0.3f;
// ★ 2026-09-06: log_030 で「最大権限 alt_thr=0.45 を出しても機体が上がらない」
//   = 実ホバースロットルが基準(旧0.30)+I上限(旧0.05)より上にあり、I項が
//   永久に届いていなかった。基準を実測寄り(下記 ALT_HOVER_THR)に上げたうえで、
//   ホバー誤差を吸収できるよう ki / I上限 を戻す。
//   ki:      0.05 -> 0.10  (積分時定数 ~2.5秒相当)
//   I_LIMIT: 0.05 -> 0.12  (基準がずれていても I 単独で寄せられる幅を確保)
// ★ 2026-09-06(2): kp 5.0/1.0 -> 0.4。スロットル権限を撤去 (ALT_THR_AUTH=0.55)
//   したので、kp が高いままだと わずかな速度誤差で 0⇔1 に叩かれる。
//   VZ_LIM=0.8 との組で、最悪 0.8*0.4=0.32 のスロットル補正に収まる。
// ★ ki 0.0 -> 0.08。ALT_HOVER_THR(0.60 固定)と「今の本当のホバー
//   スロットル」の差(電圧降下・ペイロード・空気密度で数%ずれる)を
//   I項が積分して埋める。0 だと基準ズレぶんの定常オフセット(じわじわ沈む
//   /浮く)が永久に消えない。積分時定数 ~3秒相当。上げすぎると I項が
//   行き過ぎて 0.5〜1Hz で揺れるので 0.05〜0.10 の範囲。
// ★ 2026-09-06(3): log_037 で t=6.9〜7.3s に約3cmの跳ね返り
//   (range_h 0.949m -> 0.982m)。alt_vzt は -0.80 に張り付いたままで
//   外側は無関係。中身は:
//     ・climb が目標(-0.8)に長い間追いつけず(遅れ)、誤差が5秒以上
//       負に張り付く → I項が下限 -0.12 近くまで巻き上がる
//     ・そこで climb がようやく急加速 (-0.19→-0.73 m/s) すると、
//       D項が「急な加速度」に反応して急ブレーキ(+側)を出す
//     ・巻き上がっていた I とこの D の急ブレーキが重なって alt_corr が
//       -0.3付近から +0.077 まで跳ね、alt_thr が 0.66〜0.68 (ホバー超え)
//       まで出て降下を強制的に止め、わずかに押し戻す
//   KD を下げて急ブレーキを弱め、I_LIMIT を下げて巻き上がりの寄与を絞る。
//   ki:      0.08 -> 0.06  (巻き上がる速さも少し緩める)
//   kd:      0.05 -> 0.03
//   I_LIMIT: 0.12 -> 0.06
constexpr float ALT_RATE_KI      = 0.06f;   // ホバースロットルの誤差を吸収 (上の解説参照)
constexpr float ALT_RATE_KD      = 0.03f;
// ★ 2026-09-07: 0.06 -> 0.12。I 項の仕事は「ALT_HOVER_THR の設定値と、
//   その時のバッテリー電圧/積載での本当のホバースロットルとの差」を埋めること。
//   バッテリーは満充電→終止で 15% ほど推力が落ちるので、0.06 では飛行の
//   後半を吸収しきれない。ワインドアップ対策は AltHold 側のアンチワインドアップ
//   (自分の権限飽和 + ミキサーに奪われた分の検出) でやる。
constexpr float ALT_RATE_I_LIMIT = 0.12f;   // I項の上限 [割合]。windup 防止

// ミキサーに奪われたスロットルを「飽和」とみなす閾値 [割合]。
//  Mixer::mix() は ATTITUDE_PRIORITY のときスロットルをずらす。ずれが
//  これを超えたら、高度ループはその向きへの積分を止める (AltHold.h)。
//  小さすぎると姿勢のわずかな揺れで積分が止まり、大きすぎると
//  log_037 のように奪われっぱなしのまま windup する。
constexpr float ALT_MIX_STEAL_DEAD = 0.02f;
// ★ 2026-09-06: 0.10 -> 0.6。D は climb (測距→微分→LPF 済み) をさらに
//   微分している = 鉛直加速度の推定。内側ループは測距が来た回(~30Hz)にしか
//   回らないので climb は 20ms 周期の階段状で、生の d/dt はジャンプのたびに
//   跳ねる。alpha=0.10 だとその9割がほぼそのまま thr_corr に乗り、
//   KD=0.05 と合わせて 0.1 前後のスロットル揺れを生んでいた。
//   他の D フィルタ (RATE_D_ALPHA=0.80 / ANG_D_ALPHA=0.70 /
//   FLOW_VEL_D_ALPHA=0.60) と同じ水準まで戻す。位相遅れは増えるが、
//   今はノイズによるチャタリングの方が実害が大きい。
constexpr float ALT_RATE_D_ALPHA = 0.6f;

// PID がホバースロットルから動かしてよい最大量 [割合]。
//  ブリングアップ中は余裕を持って 0.30。挙動が信用できたら 0.20 に絞る。
//  ★ 2026-09-04: 0.40 -> 0.15。ホバーが 0.30 と分かったので、権限 0.40 だと
//    出力が 0.05〜0.70 (ホバーの 1/6〜2.3倍) まで振れてしまう。0.15 なら
//    0.15〜0.45 = ホバーの ±50% で、上げ下げには十分あり暴走幅は小さい。
//  ★ 2026-09-06: 0.15 -> 0.20。log_030 で基準+0.15=0.45 が実ホバーに
//    ギリギリ届く程度で「上げる余力ゼロ」だった。基準を 0.40 に上げたので
//    0.20〜0.60 = 実ホバーの ±50%。暴走幅は基準比では変わらない。
//  ★ 2026-09-06(2): スロットルの権限リミットを撤去 (操縦者要望)。
//    log_033 で alt_corr が 8秒間ずっと -0.20 に張り付き、2.2m から
//    降りられなかった (基準0.60-0.20=0.40 が下限で、それ以上絞れない)。
//    0.55 にすると出力レンジは 0.05〜1.00 (AltHold 側の constrain で頭打ち)
//    = 実質フルレンジ。高度PIDがスロットルを 0 まで絞れる/全開にできる。
//    ▲▲ 注意: 現在 ALT_RATE_KP=5.0 / ALT_POS_KP=3.0 と非常に高い。
//       リミットが外れたので、わずかな速度誤差でスロットルが 0⇔1 に
//       叩かれる。次フライトは必ずゲインを下げること (KP: 5.0->0.4 目安)。
constexpr float ALT_THR_AUTH = 0.55f;

// ★ 2026-09-06(3): log_034 転倒の直接原因への対策。
//   高度ループの出力下限。§2 の THR_MIN_MIX(0.05)/THR_RAMP_RANGE(0.05) は
//   「地上でスロットルが0付近をふらついても姿勢補正で暴れない」ための
//   ランプ (Mixer::mix() が thr<=THR_MIN_MIX で姿勢補正ゼロ、そこから
//   THR_RAMP_RANGE ぶんかけて 0%→100% に立ち上げる)。
//   ALT_THR_AUTH=0.55 だと alt_thr が 0.60-0.55=0.05 まで落ちうるが、これは
//   ランプ帯 (0.05〜0.10) の底で、姿勢補正権限がほぼゼロになる。空中でこれが
//   起きると「速く降ろすつもり」が「姿勢制御を失う」に変わる (log_034 で
//   778ms 無補正のまま角速度がジャイロフルスケール ±250dps まで回って裏返った)。
//   高度ループの出力は、ALT_THR_AUTH をどれだけ広げてもランプ帯より確実に
//   上でしか出さないようにする。0.60 ホバーからでも 0.15 まで絞れれば
//   十分な降下力がある。
constexpr float ALT_MIN_THR_OUT = THR_MIN_MIX + THR_RAMP_RANGE + 0.05f;  // = 0.15

// ホバースロットルの基準 [割合]。★実飛行前に ANGLE ホバリングで実測して入れる。
//  0 のままだと高度ホールドは engage しない (SW_AUTO を上げても効かない)。
//  ★ POSHOLD 中はこの値だけが基準スロットルになる。プロポのスロットル位置は
//    一切参照しない (以前は未設定時に突入時のスティック値を掴んでいたため、
//    スティックが 100% だと base=1.00 になって飽和していた)。
//  ★ 2026-09-04 実測値。テレメトリのログ5本 (s5_003〜007) で、測距が有効・
//    傾き20度未満・高度がほぼ一定 (|上昇率|<0.3m/s) の区間から求めた:
//      005 = 0.277 / 006 = 0.314 / 合算 0.299 (中央値 0.276, n=15)
//    それまで入っていた 0.60 は体感値で、実測の倍以上あった。POSHOLD は
//    engage した瞬間にこの値をそのまま出すので、0.60 のままだと実ホバーの
//    倍のスロットルで上昇する。★変更したら必ず実測し直すこと。
//  ★ 2026-09-06: 0.30 -> 0.60。操縦者の実測ホバースロットルが 0.60。
//    旧 0.30 は半分しかなく、log_030 で高度ホールドは base+auth=0.45 が
//    上限だったので実ホバー(0.60)に全く届かず、機体はずっと推力不足で
//    沈んでいた (「目標に届いた瞬間に落ちる」の正体は限界に張り付いて
//    いたため)。前回 0.003〜007 の 0.30 測定は別バッテリー/ペイロード条件。
//    ALT_THR_AUTH=0.20 なので出力レンジは 0.40〜0.80 = 実ホバーの ±33%。
//
//  ★★ 2026-09-07: 0.60 -> 0.42。ここは体感ではなくログで決めること。
//    「高度がほぼ一定 (|climb|<0.1m/s) で空中 (range_h>0.3m)」の区間の
//    モーター出力平均 (m1..m4) を 4本のログから取ると:
//        log_033 = 0.407 (0.3s) / log_035 = 0.369 (2.0s)
//        log_036 = 0.421 (0.1s) / log_037 = 0.423 (1.7s)
//    どれも 0.37〜0.42 で、0.60 とは 40% 以上ずれている。
//    ★ モーター出力平均が「本当のホバースロットル」。スティック位置ではない。
//      高度ホールド中はスティックが出力に一切つながっていないので、
//      「操縦していたときのスティックが 0.60 だった」は根拠にならない。
//    0.60 のままだと base だけで実ホバーの 1.4倍を出すので、PID は常に
//    -0.18 の補正を出し続けることになり、その仕事は I 項にしかできない
//    (P は誤差がゼロなら 0)。ところが ALT_RATE_I_LIMIT は 0.06 しかなく、
//    構造的に届かない = 定常的に上昇し続ける。log_037 で目標 0.5m に対し
//    1.69m まで上がって外側ループが 89% の時間 -0.8m/s に飽和していたのは
//    これが理由。
//    ★ 変更後は必ずプロペラを付けた短いホバーで再測定すること。
//      analyze_alt_pid.py に測定を入れてある (「実測ホバースロットル」)。
constexpr float ALT_HOVER_THR = 0.42f;

