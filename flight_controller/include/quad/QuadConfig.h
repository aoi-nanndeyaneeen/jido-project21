//   遅れ、リミットサイクルになっていたと考えられる。
//   ki: 0.15 -> 0.05 (積分時定数を5秒相当まで伸ばす)。
//   I_LIMIT: 0.15 -> 0.05 (I項単独で出力(ALT_THR_AUTH=0.15)を
//     振り切れないようにし、P/D項の反応余地を残す)。
// ★ 2026-09-06(2): 0.4 -> 0.3。log_035 の減衰振動(周期~1s)対策。ALT_POS_KP
//   と同時に下げて、遅れに対する過剰反応を減らす。
constexpr float ALT_RATE_KP      = 0.3f;
// ★ 2026-09-06: log_030 で「最大権限 alt_thr=0.45 を出しても機体が上がらない」
//   = 実ホバースロットルが基準(旧0.30)+I上限(旧0.05)より上にあり、I項が
//   永久に届いていなかった。基準を実測寄り(下記 ALT_HOVER_THR)に上げたうえで、
//   ホバー誤差を吸収できるよう ki / I上限 を戻す。
//   ki:      0.05 -> 0.10  (積分時定数 ~2.5秒相当)
//   I_LIMIT: 0.05 -> 0.12  (基準がずれていても I 単独で寄せられる幅を確保)
// ★ 2026-09-06(2): kp 5.0/1.0 -> 0.4。スロットル権限を撤去 (ALT_THR_AUTH=0.55)
//   したので、kp が高いままだと わずかな速度誤差で 0⇔1 に叩かれる。
//   VZ_LIM=0.8 との組で、最悪 0.8*0.4=0.32 のスロットル補正に収まる。
// ★ ki 0.0 -> 0.08。ALT_HOVER_THR(0.60 固定)と「今の本当のホバー
//   スロットル」の差(電圧降下・ペイロード・空気密度で数%ずれる)を
//   I項が積分して埋める。0 だと基準ズレぶんの定常オフセット(じわじわ沈む
//   /浮く)が永久に消えない。積分時定数 ~3秒相当。上げすぎると I項が
//   行き過ぎて 0.5〜1Hz で揺れるので 0.05〜0.10 の範囲。
// ★ 2026-09-06(3): log_037 で t=6.9〜7.3s に約3cmの跳ね返り
//   (range_h 0.949m -> 0.982m)。alt_vzt は -0.80 に張り付いたままで
//   外側は無関係。中身は:
//     ・climb が目標(-0.8)に長い間追いつけず(遅れ)、誤差が5秒以上
//       負に張り付く → I項が下限 -0.12 近くまで巻き上がる
//     ・そこで climb がようやく急加速 (-0.19→-0.73 m/s) すると、
//       D項が「急な加速度」に反応して急ブレーキ(+側)を出す
//     ・巻き上がっていた I とこの D の急ブレーキが重なって alt_corr が
//       -0.3付近から +0.077 まで跳ね、alt_thr が 0.66〜0.68 (ホバー超え)
//       まで出て降下を強制的に止め、わずかに押し戻す
//   KD を下げて急ブレーキを弱め、I_LIMIT を下げて巻き上がりの寄与を絞る。
//   ki:      0.08 -> 0.06  (巻き上がる速さも少し緩める)
//   kd:      0.05 -> 0.03
//   I_LIMIT: 0.12 -> 0.06
constexpr float ALT_RATE_KI      = 0.06f;   // ホバースロットルの誤差を吸収 (上の解説参照)
constexpr float ALT_RATE_KD      = 0.03f;
// ★ 2026-09-07: 0.06 -> 0.12。I 項の仕事は「ALT_HOVER_THR の設定値と、
//   その時のバッテリー電圧/積載での本当のホバースロットルとの差」を埋めること。
//   バッテリーは満充電→終止で 15% ほど推力が落ちるので、0.06 では飛行の
//   後半を吸収しきれない。ワインドアップ対策は AltHold 側のアンチワインドアップ
//   (自分の権限飽和 + ミキサーに奪われた分の検出) でやる。
constexpr float ALT_RATE_I_LIMIT = 0.12f;   // I項の上限 [割合]。windup 防止

// ------------------------------------------------------------
//  § 7-3b  高度推定 (加速度Z × 測距の相補フィルタ)   -> quad/AltEstimator.h
// ------------------------------------------------------------
//  測距だけで作った climb は log_037 実測で 420ms 遅れていた。そのうち
//  約100ms は H/VZ の二重ソフトLPF。加速度計 (1000Hz・遅れほぼゼロ) で
//  速い成分を作れば、この 100ms はまるごと消せる。
//
//  ★ 有効化の手順 (いきなり true にしないこと):
//    1. ALT_USE_ACC_FUSION = false のまま1本飛ばす。
//       ログに est_h / est_vz / est_bias / acc_up が出る。
//    2. python scripts/analyze_alt_pid.py を実行。
//       「[6] 高度推定 (相補フィルタ)」が
//         ・ALT_ACC_Z_SIGN の符号が合っているか
//         ・est_vz が climb より何ms 速いか
//         ・est_bias が収束しているか
//       を判定して出す。
//    3. 符号が合っていて est_vz がまともなら true にする。
constexpr bool ALT_USE_ACC_FUSION = false;

// 相補フィルタの帯域 [rad/s]。三重極をここに置く。
//  小さい = 測距を信用しドリフトに強いが遅い / 大きい = 加速度寄りで速いが荒れる
//  2.0 rad/s ≒ 0.32Hz。これより速い成分は加速度が担当する。
constexpr float ALT_EST_W = 2.0f;

// 加速度Zの符号。IMU が上下逆マウントだと反転する。
//  ★ 判定方法: ログで機体が上昇している区間 (range_h が増える) で
//    acc_up が正になっていれば +1 で正しい。逆なら -1。
//    analyze_alt_pid.py が自動で判定して教えてくれる。
//  ★ 2026-09-09: log_007 (上下振りテスト) で判定。
//    analyze_alt_pid.py [6]: acc_up と d2(range_h)/dt2 の相関 -0.17、
//    手計算 (平滑化 + 高加速度サンプルのみ) では相関 -0.51 / 傾き -0.60。
//    d(range_h)/dt に対し climb は +0.82、est_vz は -0.26 (逆相関)。
//    -> IMU は上下逆マウント。+1.0 -> -1.0 に反転。
constexpr float ALT_ACC_Z_SIGN = -1.0f;

// 推定と測距がこれ以上食い違ったら推定を捨てて測距に合わせ直す [m]
constexpr float ALT_EST_RESET_ERR_M = 0.8f;

// 学習する加速度バイアスの上限 [m/s^2]。これを超えるならキャリブが壊れている
constexpr float ALT_EST_BIAS_LIM = 3.0f;

// ミキサーに奪われたスロットルを「飽和」とみなす閾値 [割合]。
//  Mixer::mix() は ATTITUDE_PRIORITY のときスロットルをずらす。ずれが
//  これを超えたら、高度ループはその向きへの積分を止める (AltHold.h)。
//  小さすぎると姿勢のわずかな揺れで積分が止まり、大きすぎると
//  log_037 のように奪われっぱなしのまま windup する。
constexpr float ALT_MIX_STEAL_DEAD = 0.02f;
// ★ 2026-09-06: 0.10 -> 0.6。D は climb (測距→微分→LPF 済み) をさらに
//   微分している = 鉛直加速度の推定。内側ループは測距が来た回(~30Hz)にしか
//   回らないので climb は 20ms 周期の階段状で、生の d/dt はジャンプのたびに
//   跳ねる。alpha=0.10 だとその9割がほぼそのまま thr_corr に乗り、
//   KD=0.05 と合わせて 0.1 前後のスロットル揺れを生んでいた。
//   他の D フィルタ (RATE_D_ALPHA=0.80 / ANG_D_ALPHA=0.70 /
//   FLOW_VEL_D_ALPHA=0.60) と同じ水準まで戻す。位相遅れは増えるが、
//   今はノイズによるチャタリングの方が実害が大きい。
constexpr float ALT_RATE_D_ALPHA = 0.6f;

// PID がホバースロットルから動かしてよい最大量 [割合]。
//  ブリングアップ中は余裕を持って 0.30。挙動が信用できたら 0.20 に絞る。
//  ★ 2026-09-04: 0.40 -> 0.15。ホバーが 0.30 と分かったので、権限 0.40 だと
//    出力が 0.05〜0.70 (ホバーの 1/6〜2.3倍) まで振れてしまう。0.15 なら
//    0.15〜0.45 = ホバーの ±50% で、上げ下げには十分あり暴走幅は小さい。
//  ★ 2026-09-06: 0.15 -> 0.20。log_030 で基準+0.15=0.45 が実ホバーに
//    ギリギリ届く程度で「上げる余力ゼロ」だった。基準を 0.40 に上げたので
//    0.20〜0.60 = 実ホバーの ±50%。暴走幅は基準比では変わらない。
//  ★ 2026-09-06(2): スロットルの権限リミットを撤去 (操縦者要望)。
//    log_033 で alt_corr が 8秒間ずっと -0.20 に張り付き、2.2m から
//    降りられなかった (基準0.60-0.20=0.40 が下限で、それ以上絞れない)。
//    0.55 にすると出力レンジは 0.05〜1.00 (AltHold 側の constrain で頭打ち)
//    = 実質フルレンジ。高度PIDがスロットルを 0 まで絞れる/全開にできる。
//    ▲▲ 注意: 現在 ALT_RATE_KP=5.0 / ALT_POS_KP=3.0 と非常に高い。
//       リミットが外れたので、わずかな速度誤差でスロットルが 0⇔1 に
//       叩かれる。次フライトは必ずゲインを下げること (KP: 5.0->0.4 目安)。
constexpr float ALT_THR_AUTH = 0.55f;

// ★ 2026-09-06(3): log_034 転倒の直接原因への対策。
//   高度ループの出力下限。§2 の THR_MIN_MIX(0.05)/THR_RAMP_RANGE(0.05) は
//   「地上でスロットルが0付近をふらついても姿勢補正で暴れない」ための
//   ランプ (Mixer::mix() が thr<=THR_MIN_MIX で姿勢補正ゼロ、そこから
//   THR_RAMP_RANGE ぶんかけて 0%→100% に立ち上げる)。
//   ALT_THR_AUTH=0.55 だと alt_thr が 0.60-0.55=0.05 まで落ちうるが、これは
//   ランプ帯 (0.05〜0.10) の底で、姿勢補正権限がほぼゼロになる。空中でこれが
//   起きると「速く降ろすつもり」が「姿勢制御を失う」に変わる (log_034 で
