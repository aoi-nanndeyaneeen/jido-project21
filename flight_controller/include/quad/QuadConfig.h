// ★ 2026-09-05: 1Hz前後の遅い上下振動 (50cm超えでスロットルが急に抜け、
//   30cmまで沈んでまたゆっくり上がる、を繰り返す) を受けて ki / I上限を
//   下げた。測距(約33ms周期)+ RANGE_H_ALPHA/RANGE_VZ_ALPHA の二重LPFで
//   フィードバックに数百msの遅れがあるのに ki=0.15 (積分時定数1.7秒) は
